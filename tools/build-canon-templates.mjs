// Turn the extracted canon into an ES module the app can render.
//
// apply-design's central failure mode is RE-IMPLEMENTING the design with the
// app's own components, which loses every property the app cannot express. The
// defence is to not re-implement it at all: the app renders the canon's OWN
// markup, byte for byte, and only the DATA is bound in. So this file does no
// design work whatsoever. It copies.
//
// Run: node tools/build-canon-templates.mjs
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const EX = join(ROOT, 'design', 'extracted');
const SCREENS = readdirSync(EX).filter((f) => f.endsWith('.html')).map((f) => f.replace('.html', ''));

// Every image the app or the design tool holds, indexed by content hash. The
// design inlines its sleeves as data URIs; hashing tells us WHICH SONG each one
// is, so the shipped template can carry the group name and the renderer can
// bind the real file. The alternative is reading the pictures and typing names,
// which is guessing with extra steps.
const sha = (b) => createHash('sha1').update(b).digest('hex');
const known = new Map();
const groupFrom = (p) => p.replace(/^.*[\/]/, '').replace(/^sleeve-/, '').replace(/\.(jpg|jpeg|png)$/i, '');
for (const dir of [join(ROOT, 'art', '_full'), join(ROOT, 'art', '512'), join(ROOT, 'art', '128'),
                   join(ROOT, 'design-2026-08', 'claude-design-v2', 'uploads')]) {
  if (!existsSync(dir)) continue;
  for (const f of readdirSync(dir)) {
    if (!/\.(jpg|jpeg|png)$/i.test(f)) continue;
    const h = sha(readFileSync(join(dir, f)));
    if (!known.has(h)) known.set(h, groupFrom(f));
  }
}

const out = ['// GENERATED by tools/build-canon-templates.mjs from design/extracted/.',
  '// This is the design, byte for byte. Do NOT hand-edit: fix the design in',
  '// Claude Design, re-extract, and re-run the builder. A hand-edit here is the',
  '// exact drift this whole method exists to prevent.',
  'export const CANON = {'];
const inherited = {};
let unmatched = 0;

for (const s of SCREENS) {
  let html = readFileSync(join(EX, `${s}.html`), 'utf8');
  const before = html.length;
  html = html.replace(/\s*data-box="[^"]*"/g, '').replace(/\s*data-dx="[^"]*"/g, '');
  // the prototype's own additions never ship
  html = html.replace(/\s*class="hot"/g, '').replace(/\s*data-go="[^"]*"/g, '').replace(/\s*data-back="[^"]*"/g, '');
  // The design inlines its sleeves as data URIs: 473KB across the set, for
  // pictures the app already has on disk and will bind at render time. Replace
  // each with the group it is, resolved by content hash.
  let stripped = 0;
  html = html.replace(/src="data:image\/[a-z]+;base64,([^"]+)"/g, (_, b64) => {
    stripped++;
    const g = known.get(sha(Buffer.from(b64, 'base64')));
    if (!g) { unmatched++; return 'src="" data-art=""'; }
    return `src="" data-art="${g}"`;
  });
  const meta = JSON.parse(readFileSync(join(EX, `${s}.json`), 'utf8'));
  inherited[s] = meta.inherited;
  out.push(`  ${JSON.stringify(s)}: ${JSON.stringify(html)},`);
  console.log(`${s.padEnd(12)} ${String(Math.round(before / 1024)).padStart(4)}KB -> ${String(Math.round(html.length / 1024)).padStart(4)}KB` +
    (stripped ? `   ${stripped} sleeve${stripped > 1 ? 's' : ''} bound by group` : ''));
}
out.push('};\n');
// The typography the canon INHERITS from its page. The card declares no font of
// its own, so mounting it in a default 16px/normal document grows every box by
// a fraction. Whoever mounts the canon applies this first.
out.push('export const CANON_INHERITED = ' + JSON.stringify(inherited, null, 2) + ';\n');

// The isolation rule in style.css restores exactly one non-inherited property
// after standing the app layer down. If the canon ever stops being authored
// under a border-box reset, that rule becomes a lie, so check it here rather
// than discover it as a screen full of red pixels.
const boxes = new Set(Object.values(inherited).map((i) => i && i.boxSizing).filter(Boolean));
if (boxes.size && !(boxes.size === 1 && boxes.has('border-box'))) {
  console.log(`
CANON BASELINE CHANGED: box-sizing is ${[...boxes].join(', ')}, not border-box.`);
  console.log('Update the .canon-root isolation rule in style.css to match, then re-run.');
  process.exit(1);
}

const dest = join(ROOT, 'js', 'canon-templates.mjs');
writeFileSync(dest, out.join('\n'));
const kb = Math.round(out.join('\n').length / 1024);
console.log(`\nwrote ${dest}  (${SCREENS.length} screens, ${kb}KB)`);
if (unmatched) { console.log(`\n${unmatched} sleeve(s) could not be matched to a file on disk.`); process.exit(1); }
